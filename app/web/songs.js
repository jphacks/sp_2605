const SEMITONE = { C: 0, D: 2, E: 4, F: 5, G: 7, A: 9, B: 11 };

export function noteToFreq(name) {
  const m = /^([A-G])(#?)(\d)$/.exec(name);
  const midi = 12 * (Number(m[3]) + 1) + SEMITONE[m[1]] + (m[2] ? 1 : 0);
  return 440 * 2 ** ((midi - 69) / 12);
}

// 低い音ほど左の穴。ド・レ→0、ミ・ファ→1、ソ・ラ→2、シ・高いド→3
export function holeFor(name) {
  const letter = name[0];
  const octave = Number(name.at(-1));
  if (octave >= 6) return 3;
  if (octave <= 4) return 0;
  return { C: 0, D: 0, E: 1, F: 1, G: 2, A: 2, B: 3 }[letter];
}
